# -*- coding: utf-8 -*-
"""
unfont.py — перевод древнееврейского текста пособия НББС из шрифтовой
кодировки BibleWorks (BWHEBB) в Unicode.

ЗАЧЕМ
-----
В PDF пособия еврейские слова записаны НЕ юникодом, а латиницей: каждый
латинский символ — это глиф еврейского шрифта. `rb'D"` — это דָּבָר,
`~yhil{a/` — это אֱלֹהִים. Слой такой кодировки не повреждён (в отличие
от OCR греческого учебника): это обратимая подстановка, и восстановление
здесь механическое, а не вероятностное.

КАК УСТРОЕНА КОДИРОВКА
----------------------
1. Строка хранится в ВИЗУАЛЬНОМ порядке (слева направо на экране), то есть
   в обратном относительно логического еврейского (справа налево).
2. Знак огласовки стоит в строке ПОСЛЕ своей согласной.
3. Конечные формы букв — отдельные символы (`~` = ם, `!` = ן, `$` = ך,
   `@` = ף, `#` = ץ).
4. Заглавная латинская буква = та же согласная с дагешем (`b`→ב, `B`→בּ).

Отсюда алгоритм: идём по строке слева направо, собираем «единицы»
(согласная + её знаки), затем переворачиваем список единиц.

ПОРЯДОК ЗНАКОВ ВНУТРИ ЕДИНИЦЫ
-----------------------------
Выдаём в принятом для еврейской Библии порядке:
согласная, дагеш/маппик, точка шин/син, огласовка, метег, ударение.
NFC-нормализация НЕ применяется намеренно: канонический порядок Unicode
сортирует знаки по combining class и ставит огласовку ПЕРЕД дагешем
(qamets ccc=18 < dagesh ccc=21), чего нет ни в BHS, ни в WLC, и что ломает
отрисовку в части шрифтов. Тексты на библейском иврите принято хранить
в логическом порядке, а не в NFC.

ЗАПУСК
------
    python unfont.py raw/lesson-03.txt          # в stdout
    python unfont.py raw/*.txt -o ../lessons/   # в файлы
    python unfont.py --self-test                # проверка таблицы

Еврейские отрезки в raw/*.txt размечены угловыми скобками U+27E8/U+27E9:
    слово ⟨rb'D"⟩ значит «слово»
Разметка обязательна: без неё «Qal», «sg.», «BHS» неотличимы от еврейских
слов и были бы «переведены» в бессмыслицу.
"""

import argparse
import io
import os
import re
import sys

# Консоль Windows по умолчанию cp1251 — еврейские буквы в неё не пишутся
# и скрипт падает на печати. Переключаем вывод на UTF-8 явно.
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    sys.stderr.reconfigure(encoding='utf-8', errors='replace')

# ---------------------------------------------------------------- согласные
# Источник таблицы — сам учебник, §1.1 (алфавит), §1.4 (конечные формы),
# §1.5 (бегадкефат и «слабый» дагеш). Заглавная = дагеш внутри буквы.
CONSONANTS = {
    'a': 'א',                    # א алеф
    'b': 'ב', 'B': 'בּ',  # ב / בּ бет
    'g': 'ג', 'G': 'גּ',  # ג / גּ гимел
    'd': 'ד', 'D': 'דּ',  # ד / דּ далет
    'h': 'ה', 'H': 'הּ',  # ה / הּ хе (H — маппик, §3.10)
    'w': 'ו', 'W': 'וּ',  # ו / וּ вав (W — шурек, §2.5)
    'z': 'ז', 'Z': 'זּ',  # ז / זּ заин
    'x': 'ח',                    # ח хет (гортанный, дагеша не бывает)
    'j': 'ט', 'J': 'טּ',  # ט / טּ тет
    'y': 'י', 'Y': 'יּ',  # י / יּ йод
    'k': 'כ', 'K': 'כּ',  # כ / כּ каф
    '$': 'ך', '&': 'ךּ',  # ך / ךּ каф конечный
    # §1.11: «каф на конце часто встречается с двумя точками» — это шва
    # под конечным кафом (מֶלֶךְ). В шрифте у неё отдельный глиф.
    '%': 'ךְ',
    'l': 'ל', 'L': 'לּ',  # ל / לּ ламед
    'm': 'מ', 'M': 'מּ',  # מ / מּ мем
    '~': 'ם',                    # ם мем конечный
    'n': 'נ', 'N': 'נּ',  # נ / נּ нун
    '!': 'ן',                    # ן нун конечный
    's': 'ס', 'S': 'סּ',  # ס / סּ самех
    '[': 'ע',                    # ע айин (гортанный)
    'p': 'פ', 'P': 'פּ',  # פ / פּ пе
    '@': 'ף',                    # ף пе конечный
    'c': 'צ', 'C': 'צּ',  # צ / צּ цаде
    '#': 'ץ',                    # ץ цаде конечный
    'q': 'ק', 'Q': 'קּ',  # ק / קּ коф
    'r': 'ר', 'R': 'רּ',  # ר / רּ реш (дагеш крайне редок)
    'f': 'שׂ', 'F': 'שּׂ',  # שׂ / שּׂ син
    'v': 'שׁ', 'V': 'שּׁ',  # שׁ / שּׁ шин
    't': 'ת', 'T': 'תּ',  # ת / תּ тав
    # Составные глифы местоименных суффиксов (§9.2). В шрифте это один
    # символ, в юникоде — согласная со своей огласовкой.
    '^': 'ךָ',   # ךָ  суффикс 2 л. м. р. ед. ч. «твой» (^b.b'l. = לְבָבְךָ)
    'A': 'וֹ',   # וֹ  суффикс 3 л. м. р. ед. ч. «его» (AsWs = סוּסוֹ)
}

# ---------------------------------------------------------------- огласовки
# §2.3-2.6. У части знаков в шрифте есть позиционные варианты (широкая и
# узкая буква под знаком) — в юникоде это один и тот же символ.
VOWELS = {
    ';': 'ַ', ':': 'ַ',     # ַ  патах (`:` — вариант в союзе `w:` wa, §5.7.3)
    "'": 'ָ', '"': 'ָ',     # ָ  камец (и камец хатуф — §3.7)
    ',': 'ֶ', '<': 'ֶ',     # ֶ  сегол
    'e': 'ֵ', 'E': 'ֵ',     # ֵ  цере
    'i': 'ִ', 'I': 'ִ',     # ִ  хирек
    'o': 'ֹ', 'O': 'ֹ', '{': 'ֹ',  # ֹ  холем
    'u': 'ֻ', 'U': 'ֻ',     # ֻ  киббуц
    '.': 'ְ', '>': 'ְ',     # ְ  шва
    ']': 'ֲ',                    # ֲ  хатеф-патах
    '/': 'ֱ',                    # ֱ  хатеф-сегол
    '\\': 'ֳ',                   # ֳ  хатеф-камец
}

# ------------------------------------------------------- ударение и метег
# §3.3: значок ударения ставится НАД ударным слогом, когда ударение не на
# последнем слоге (`rp,sñe` = סֵ֫פֶר). Передаём его знаком ֫ (U+05AB, ole) —
# это принятая в грамматиках пометка ударения, не библейский акцент.
# §3.7.3: метег — вертикальная чёрточка ПОД буквой (`~yTiB'(` = בָּֽתִּים).
MARKS = {
    'ñ': '֫', 'ò': '֫', 'ó': '֫',   # ֫ ударение (над)
    '(': 'ֽ', ')': 'ֽ',                  # ֽ метег (под)
}

# Знаки, не привязанные к согласной
STANDALONE = {
    '-': '־',   # ־ маккеф (§6.3)
    '|': '|',        # разделитель слогов в учебнике (§3.2) — оставляем как есть
}

# Порядок знаков внутри одной «единицы» (согласная + её знаки).
# Меньше — раньше. Совпадает с тем, как хранит текст BHS/WLC.
_MARK_ORDER = {
    'ּ': 0,   # дагеш / маппик
    'ׁ': 1,   # точка шин
    'ׂ': 1,   # точка син
    'ֽ': 3,   # метег
    '֫': 4,   # ударение
}
_VOWEL_SET = set(VOWELS.values())


def _mark_rank(ch):
    if ch in _VOWEL_SET:
        return 2
    return _MARK_ORDER.get(ch, 5)


# ------------------------------------------------------------- исключения
# Слова, где общее правило «огласовка относится к предыдущей согласной»
# не работает, потому что шрифт рисует знак не там, где он стоит логически.
# Такие случаи наперечёт, и каждый выверен по BHS отдельно. Держим их
# таблицей, а не усложняем правило: оно проверено на всём остальном тексте.
EXCEPTIONS = {
    # Иерусалим пишется дефектно: хирек стоит под ЛАМЕДОМ (לִַם), а шрифт
    # рисует его глиф после конечного мема. BHS: יְרוּשָׁלִַם
    '~ilñ;v\'Wry>': 'יְרוּשָׁ'
                    'לִַם',
    '~il;v\'Wry>':  'יְרוּשָׁ'
                    'לִַם',
}


def decode_token(token):
    """Одно еврейское слово из шрифтовой кодировки — в юникод."""
    if token in EXCEPTIONS:
        return EXCEPTIONS[token]
    units = []          # каждая единица: [база, [знаки]]
    for ch in token:
        if ch in CONSONANTS:
            base = CONSONANTS[ch]
            # у 'v'/'V'/'f'/'F' в базе уже есть дагеш и точка — разбираем
            units.append([base[0], list(base[1:])])
        elif ch in VOWELS:
            if units:
                units[-1][1].append(VOWELS[ch])
        elif ch in MARKS:
            if units:
                units[-1][1].append(MARKS[ch])
        elif ch in STANDALONE:
            units.append([STANDALONE[ch], []])
        # всё прочее (цифры, скобки) молча выбрасываем: внутри ⟨⟩ его быть
        # не должно, а если попало — это ошибка разметки, её ловит --audit
    out = []
    for base, marks in reversed(units):
        marks.sort(key=_mark_rank)
        out.append(base + ''.join(marks))
    return ''.join(out)


# Отрезок между ⟨ и ⟩ может содержать несколько слов через пробел и
# служебные скобки — например `⟨rb'D"⟩`. Пробелы внутри отрезка означают
# границу слов; в еврейском порядке слова тоже идут справа налево.
def decode_run(run):
    parts = run.split(' ')
    words = [decode_token(p) for p in parts if p != '']
    return ' '.join(reversed(words)) if len(words) > 1 else ''.join(words)


RUN_RE = re.compile('⟨(.*?)⟩', re.S)


def decode_text(text):
    return RUN_RE.sub(lambda m: decode_run(m.group(1)), text)


# ---------------------------------------------------------------- проверка
# Контрольные слова: слева — как в PDF, справа — как должно быть.
# Правые части выверены по Westminster Leningrad Codex / BHS.
SELF_TEST = [
    # (шрифтовая запись, ожидаемые кодовые точки, глосса)
    #
    # Ожидание записано КОДОВЫМИ ТОЧКАМИ, а не буквами, намеренно: редактор
    # или буфер обмена молча приводит еврейскую строку к NFC и переставляет
    # огласовку перед дагешем (05B6 05BC вместо 05BC 05B6). Тест на литералах
    # начал бы падать на верном выводе — что здесь один раз и случилось.
    ("rb'D\"",   '05D3 05BC 05B8 05D1 05B8 05E8',                'дабар «слово»'),
    ('~yhil{a/',  '05D0 05B1 05DC 05B9 05D4 05B4 05D9 05DD',      'элохим «Бог»'),
    ("lj;q'",     '05E7 05B8 05D8 05B7 05DC',                     'катал «убил»'),
    ('hw"hy>',    '05D9 05B0 05D4 05D5 05B8 05D4',                'ЙХВХ'),
    ("hr\"wOT",  '05EA 05BC 05D5 05B9 05E8 05B8 05D4',           'тора «закон»'),
    ('!Be',       '05D1 05BC 05B5 05DF',                          'бен «сын»'),
    ('lyjiq.hi',  '05D4 05B4 05E7 05B0 05D8 05B4 05D9 05DC',      'хикт+ил (хифил)'),
    ('lJeqi',     '05E7 05B4 05D8 05BC 05B5 05DC',                'киттэл (пиэль)'),
    ('lj;q.nI',   '05E0 05B4 05E7 05B0 05D8 05B7 05DC',           'никтал (нифал)'),
    ('sWs',       '05E1 05D5 05BC 05E1',                          'сус «конь»'),
    ('~ve',       '05E9 05C1 05B5 05DD',                          'шем «имя»'),
    ('#r<a,',     '05D0 05B6 05E8 05B6 05E5',                     'эрец «земля»'),
    ('%l,m,',     '05DE 05B6 05DC 05B6 05DA 05B0',               'мелех «царь»'),
    ('%r<D<',     '05D3 05BC 05B6 05E8 05B6 05DA 05B0',          'дэрех «дорога»'),
    ('~yhiloawE', '05D5 05B5 05D0 05DC 05B9 05D4 05B4 05D9 05DD', 'вэлохим «и Бог» (§5.7.3)'),
    # ударение и метег — знаки, а не огласовки; проверяем, что встают после
    ('rp,sñe',    '05E1 05B5 05AB 05E4 05B6 05E8'      ,           'сэфер с ударением (§3.3)'),
    ('~yTiB\'(',  '05D1 05BC 05B8 05BD 05EA 05BC 05B4 05D9 05DD', 'батим с метегом (§3.7.3)'),
    # составные глифы местоименных суффиксов
    ('AsWs',      '05E1 05D5 05BC 05E1 05D5 05B9',                'сусо «его конь» (§9.5)'),
    ("^b.b'l.",   '05DC 05B0 05D1 05B8 05D1 05B0 05DA 05B8',      'леваве́ха (Втор. 6:5)'),
]


def _points(s):
    return ' '.join('%04X' % ord(c) for c in s)


def self_test(verbose=True):
    bad = 0
    for src, want, gloss in SELF_TEST:
        got = decode_token(src)
        ok = (_points(got) == want)
        if not ok:
            bad += 1
        if verbose:
            mark = 'ok  ' if ok else 'FAIL'
            line = '%s %-12s -> %-14s %s' % (mark, src, got, gloss)
            if not ok:
                line += ('\n         получено:  ' + _points(got) +
                         '\n         ожидалось: ' + want)
            sys.stdout.write(line + '\n')
    if verbose:
        sys.stdout.write('\n%d из %d\n' % (len(SELF_TEST) - bad, len(SELF_TEST)))
    return bad == 0


# ------------------------------------------------------------------ аудит
# Каждый декодированный отрезок — в список, чтобы результат можно было
# просмотреть глазами и сверить со словарём, а не принимать на веру.
def audit(text):
    rows = []
    for m in RUN_RE.finditer(text):
        src = m.group(1)
        out = decode_run(src)
        unknown = sorted(set(
            ch for ch in src
            if ch not in CONSONANTS and ch not in VOWELS
            and ch not in MARKS and ch not in STANDALONE and ch != ' '
        ))
        rows.append((src, out, ''.join(unknown)))
    return rows


# Сводка по всему корпусу сразу — числа для restoration-report.md берутся
# отсюда, а не пишутся руками.
def stats(paths):
    runs = words = 0
    glyphs = {}
    unknown = {}
    exc = 0
    for path in paths:
        text = io.open(path, encoding='utf-8').read()
        for m in RUN_RE.finditer(text):
            src = m.group(1)
            runs += 1
            for tok in src.split(' '):
                if not tok:
                    continue
                words += 1
                if tok in EXCEPTIONS:
                    exc += 1
            for ch in src:
                if ch == ' ':
                    continue
                known = (ch in CONSONANTS or ch in VOWELS
                         or ch in MARKS or ch in STANDALONE)
                bucket = glyphs if known else unknown
                bucket[ch] = bucket.get(ch, 0) + 1
    return {'files': len(paths), 'runs': runs, 'words': words,
            'glyphs': glyphs, 'unknown': unknown, 'exceptions': exc}


def main():
    ap = argparse.ArgumentParser(description='BWHEBB -> Unicode Hebrew')
    ap.add_argument('files', nargs='*')
    ap.add_argument('-o', '--outdir', help='каталог для результата')
    ap.add_argument('--self-test', action='store_true')
    ap.add_argument('--audit', action='store_true',
                    help='список всех отрезков: исходник, результат, неизвестные символы')
    ap.add_argument('--stats', action='store_true',
                    help='сводка по всем файлам: отрезки, слова, задействованные глифы')
    args = ap.parse_args()

    if args.self_test:
        sys.exit(0 if self_test() else 1)

    if not args.files:
        ap.error('нечего обрабатывать')

    if args.stats:
        st = stats(args.files)
        sys.stdout.write('файлов:              %d\n' % st['files'])
        sys.stdout.write('отрезков ⟨…⟩:        %d\n' % st['runs'])
        sys.stdout.write('еврейских слов:     %d\n' % st['words'])
        sys.stdout.write('из них по списку исключений: %d\n' % st['exceptions'])
        sys.stdout.write('разных глифов:      %d из %d в таблице\n'
                         % (len(st['glyphs']),
                            len(CONSONANTS) + len(VOWELS) + len(MARKS) + len(STANDALONE)))
        sys.stdout.write('неизвестных глифов: %d%s\n'
                         % (len(st['unknown']),
                            ('  ??? ' + ''.join(sorted(st['unknown']))) if st['unknown'] else ''))
        sys.exit(1 if st['unknown'] else 0)

    for path in args.files:
        text = io.open(path, encoding='utf-8').read()
        if args.audit:
            for src, out, unknown in audit(text):
                flag = ('  ??? ' + unknown) if unknown else ''
                sys.stdout.write('%-24s %s%s\n' % (src, out, flag))
            continue
        result = decode_text(text)
        if args.outdir:
            name = os.path.basename(path)
            if name.endswith('.txt'):
                name = name[:-4] + '.md'
            dest = os.path.join(args.outdir, name)
            io.open(dest, 'w', encoding='utf-8').write(result)
            sys.stdout.write('%s -> %s\n' % (path, dest))
        else:
            sys.stdout.write(result)


if __name__ == '__main__':
    main()
